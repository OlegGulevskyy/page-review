#!/usr/bin/env node
// MCP server (stdio): lets a coding agent open pages for review, read comment threads,
// and reply while leaving resolution to the user. Connect with page-review setup.
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { api, openTarget } from "./control.js";
import { VERSION } from "./package.js";

const AGENT_NAME = process.env.PAGE_REVIEW_AGENT_NAME || "Agent";
const server = new McpServer({ name: "page-review", version: VERSION });

const text = (value) => ({ content: [{ type: "text", text: typeof value === "string" ? value : JSON.stringify(value, null, 2) }] });
const wrap = (fn) => async (args) => {
  try {
    return text(await fn(args));
  } catch (e) {
    return { ...text(`Error: ${e.message}`), isError: true };
  }
};

server.registerTool(
  "review_open",
  {
    title: "Open a page for review",
    description:
      "Serve a local HTML file (or directory) or proxy a running dev server so the user can leave comment threads " +
      "on it in their browser. Returns the review URL to give the user, and the site_id. Every comment is answered by " +
      "a local agent run (claude or codex, see runner) started in project_root: the surrounding project (nearest .git, " +
      "package.json, CLAUDE.md…), detected for files, to be given for dev servers. Calling it again for the same file or " +
      "server returns the same site and URL; existing threads are kept. For served files the threads are stored next to " +
      "them in <directory>/.page-review.json.",
    inputSchema: {
      target: z.string().describe("Absolute path to an .html file or a directory, or a dev server URL such as http://localhost:3000/dashboard"),
      project_root: z.string().optional().describe("Project directory the agent runs in (and searches for context). Detected for files; needed for dev servers. Empty string goes back to auto-detection."),
      runner: z.enum(["claude", "codex", "webhook", "none"]).optional().describe("Who answers this site's comments; default is the global runner (claude). 'webhook' POSTs to webhook_url instead."),
      webhook_url: z.string().optional().describe("Only for runner 'webhook': URL to POST to when the user writes. Empty string removes it."),
      context: z
        .string()
        .optional()
        .describe(
          "Notes for whoever answers the comments later, possibly a fresh agent with no memory of this session: what the " +
            "page is, which files are its real source (e.g. 'generated by overview.py, edit that and run python3 overview.py'), " +
            "the project directory, and anything to keep consistent. Returned with every thread.",
        ),
    },
  },
  wrap(async ({ target, webhook_url, context, project_root, runner }) => {
    const { site, url } = await openTarget(target, webhook_url, context, { project_root, runner });
    return {
      review_url: url,
      site_id: site.id,
      kind: site.kind,
      root: site.root || site.target,
      project_root: site.projectRoot || null,
      threads_file: site.kind === "dir" ? `${site.root}/.page-review.json` : null,
      runner: site.runner,
      ...(site.runner === "webhook" ? { webhook: site.webhook_effective || null, webhook_scope: site.webhook_scope } : {}),
      context: site.context || null,
    };
  }),
);

server.registerTool(
  "review_list",
  {
    title: "List review threads",
    description:
      "List comment threads. needs_reply is true when the user wrote last on an open thread. Each entry gives the " +
      "page, the local file (for served files) and the quoted text the comment is attached to.",
    inputSchema: {
      status: z.enum(["open", "resolved", "all"]).default("open"),
      site_id: z.string().optional().describe("Only threads on this site"),
    },
  },
  wrap(async ({ status, site_id }) => {
    const q = new URLSearchParams({ status });
    if (site_id) q.set("site", site_id);
    const list = await api("GET", `/threads?${q}`);
    return list.length ? list : "No threads.";
  }),
);

server.registerTool(
  "review_get",
  {
    title: "Read a review thread",
    description:
      "Read one thread in full: every message, the anchor (exact quoted text with surrounding prefix/suffix, CSS " +
      "selector, nearest heading as `section`, or the element tag and snippet for element comments; `original` is the " +
      "text first commented on when the page has since changed it), the page URL, " +
      "the local file, project_root (the project directory the file lives in: read its CLAUDE.md/AGENTS.md and search it " +
      "for context), site_context (notes on what the page is and where its source lives) and context_paths (folders or " +
      "files the user @-mentioned for context: read them as reference, do not edit them). Marks the thread as being " +
      "worked on, so the user sees that you picked it up.",
    inputSchema: { thread_id: z.string() },
  },
  wrap(async ({ thread_id }) => {
    const t = await api("GET", `/threads/${thread_id}`);
    if (t.needs_reply) await api("POST", `/threads/${thread_id}/status`, { agent: "working" });
    return {
      id: t.id,
      status: t.status,
      page: t.page,
      url: t.url,
      file: t.file,
      project_root: t.project_root,
      site_context: t.site_context,
      context_paths: t.context_paths,
      anchor: t.anchor,
      messages: t.messages.map((m) => ({ author: m.author, text: m.text, at: m.at })),
    };
  }),
);

server.registerTool(
  "review_reply",
  {
    title: "Reply to a review thread",
    description:
      "Post a reply in a thread; it appears live in the user's browser. Say what you changed (and where, if it was " +
      "elsewhere on the page) or answer the question. Replies leave the thread open for the user to review and resolve. " +
      "Short markdown works: **bold**, `code`, [links](https://…). If you rewrote the commented text itself, pass " +
      "its new wording as anchor_text so the comment stays attached to it and shows what it was renamed from.",
    inputSchema: {
      thread_id: z.string(),
      text: z.string(),
      anchor_text: z.string().optional().describe("The commented text as it now reads on the page, when your change rewrote it"),
    },
  },
  wrap(async ({ thread_id, text: body, anchor_text }) => {
    const t = await api("POST", `/threads/${thread_id}/messages`, { author: "agent", name: AGENT_NAME, text: body, anchor_text });
    return { id: t.id, status: t.status, messages: t.messages.length };
  }),
);

server.registerTool(
  "review_set_status",
  {
    title: "Reopen a review thread",
    description: "Reopen a thread without replying. Only the user can resolve threads in the browser.",
    inputSchema: { thread_id: z.string(), status: z.enum(["open"]) },
  },
  wrap(async ({ thread_id, status }) => {
    const t = await api("POST", `/threads/${thread_id}/status`, { status, agent: "idle", author: "agent" });
    return { id: t.id, status: t.status };
  }),
);

server.registerTool(
  "review_set_webhook",
  {
    title: "Register a webhook",
    description:
      "Register the URL to POST to when the user comments: for a project (every page served from under " +
      "project_root, the usual case: one T3 webhook task per T3 project), for one site, or as the default. " +
      "Empty url removes it. Resolution order: site, then project, then default.",
    inputSchema: {
      url: z.string().describe("Webhook URL, or empty string to remove"),
      project_root: z.string().optional().describe("Project directory (the project_root of a site)"),
      site_id: z.string().optional(),
    },
  },
  wrap(async ({ url, project_root, site_id }) => {
    if (site_id) return { site_id, webhook: (await api("PATCH", `/sites/${site_id}`, { webhook: url })).webhook || null };
    if (project_root) {
      const c = await api("PATCH", "/config", { project_webhook: { root: project_root, url } });
      return { project_root, webhook: c.webhooks?.[project_root] || null };
    }
    return { default_webhook: (await api("PATCH", "/config", { defaultWebhook: url })).defaultWebhook || null };
  }),
);

server.registerTool(
  "review_sites",
  {
    title: "List review sites",
    description: "List the files/directories and dev servers registered for review, with their URLs, project roots and runners.",
    inputSchema: {},
  },
  wrap(async () => (await api("GET", "/sites")).map((s) => ({ site_id: s.id, kind: s.kind, root: s.root || s.target, project_root: s.projectRoot || null, threads_file: s.threads_file, url: s.url, runner: s.runner, ...(s.runner === "webhook" ? { webhook: s.webhook_effective || null } : {}) }))),
);

await server.connect(new StdioServerTransport());
